"""
/books - the former monolith, now a service of its own (Unit 04).
The API key check moved to the gateway: writes (POST/PUT/DELETE) without a
valid X-API-Key never reach this service. It publishes no port.
"""
from fastapi import APIRouter, Depends, HTTPException, Response, status
from sqlalchemy import or_, select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from ..db import get_db
from ..models import Book
from ..schemas import BookIn, BookOut, BookUpdate

router = APIRouter(prefix="/books", tags=["books"])


@router.get("", response_model=list[BookOut])
def list_books(search: str | None = None, author: str | None = None,
               db: Session = Depends(get_db)):
    query = select(Book).order_by(Book.id)
    if search:                         # title OR author, case-insensitive
        pattern = f"%{search}%"
        query = query.where(or_(Book.title.ilike(pattern), Book.author.ilike(pattern)))
    if author:                         # stretch goal: GET /books?author=Orwell
        query = query.where(Book.author.ilike(f"%{author}%"))
    return db.scalars(query).all()


@router.get("/{book_id}", response_model=BookOut)
def get_book(book_id: int, db: Session = Depends(get_db)):
    book = db.get(Book, book_id)
    if book is None:
        raise HTTPException(status_code=404, detail="Book not found")
    return book


@router.post("", response_model=BookOut, status_code=status.HTTP_201_CREATED)
def create_book(payload: BookIn, response: Response, db: Session = Depends(get_db)):
    book = Book(**payload.model_dump())
    db.add(book)
    try:
        db.commit()
    except IntegrityError:    # UNIQUE(isbn) enforced by the database itself
        db.rollback()
        raise HTTPException(status_code=409, detail=f"ISBN {payload.isbn} already exists")
    db.refresh(book)          # reload to get the id generated by the database
    # HTTP cheat sheet (Unit 04bis): "Created something -> 201 + Location: /books/43"
    response.headers["Location"] = f"/books/{book.id}"
    return book


@router.put("/{book_id}", response_model=BookOut)
def update_book(book_id: int, payload: BookUpdate, db: Session = Depends(get_db)):
    book = db.get(Book, book_id)
    if book is None:
        raise HTTPException(status_code=404, detail="Book not found")
    # only the fields sent by the client (exclude_unset=True)
    for field, value in payload.model_dump(exclude_unset=True).items():
        setattr(book, field, value)
    db.commit()
    db.refresh(book)
    return book


@router.delete("/{book_id}", status_code=status.HTTP_204_NO_CONTENT)
def delete_book(book_id: int, db: Session = Depends(get_db)):
    book = db.get(Book, book_id)
    if book is None:
        raise HTTPException(status_code=404, detail="Book not found")
    db.delete(book)
    db.commit()
    return Response(status_code=status.HTTP_204_NO_CONTENT)   # 204 = success, empty body
